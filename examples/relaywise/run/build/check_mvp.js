// FICTIONAL example (Relaywise). Headless check (~10s): page loads, main flow clicks through, no errors. Run: node check_mvp.js
const { chromium } = require('playwright'); const http = require('http'), fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const srv = http.createServer((q, r) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0]));
  fs.readFile(f, (e, b) => { if (e) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'Content-Type': f.endsWith('.json') ? 'application/json' : 'text/html' }); r.end(b); }); });
(async () => {
  await new Promise(ok => srv.listen(0, ok)); const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  const t = (label, ok) => { console.log((ok ? 'PASS ' : 'FAIL ') + label); if (!ok) errs.push(label); };
  const head = () => p.textContent('#headline');
  await p.goto(`http://localhost:${srv.address().port}/build/mvp.html`); await p.waitForSelector('body[data-ready="1"]');
  t('1 setup shows ticket volume', (await p.textContent('#s1')).includes('13,537 tickets'));
  await p.click('#s1 .btn.primary');
  t('2 brief: recommended plan £349k', (await head()).startsWith('£349k'));
  t('why panel names Billing disputes', (await p.textContent('#s2 .issue')).includes('Billing disputes'));
  t('wrong answers shown', (await p.textContent('#wrongTotal')).includes('197'));
  await p.click('#headline .num'); t('method opens from the number', await p.isVisible('#howDrawer.open')); await p.click('#howDrawer .btn');
  await p.click('#plan-review'); t('review everything → £271k', (await head()).startsWith('£271k'));
  await p.click('#plan-auto'); t('auto everything → −£151k', (await head()).startsWith('−£151k'));
  await p.click('#plan-recommended');
  t('rollout plan drafted', (await p.textContent('.terms')).includes('Guardrail'));
  t('breakdown closed by default', !(await p.evaluate(() => document.getElementById('more').open)));
  await p.evaluate(() => { document.getElementById('more').open = true; }); await p.fill('#costMajor', '800'); await p.dispatchEvent('#costMajor', 'change');
  t('serious error at £800 → £225k', (await head()).startsWith('£225k'));
  await p.evaluate(() => { st.costMajor = null; render(); });
  await p.click('#s2 .catLink'); t('3 category detail: Billing disputes', (await p.textContent('#s3')).includes('Billing disputes'));
  await p.click('#example'); t('labelled set → auto-resolve', (await p.textContent('#recAfter')).includes('Auto-resolve')); t('plan → £507k', (await p.textContent('#netAfter')).startsWith('£507k'));
  await p.click('#applyL'); await p.click('#s3 .btn.secondary'); t('brief uses the labelled set → £507k', (await head()).startsWith('£507k'));
  await p.click('#toSend'); await p.click('#send'); t('4 sent for approval', await p.isVisible('#sentOk'));
  console.log(errs.length ? 'ERRORS: ' + errs.join(' | ') : 'All checks pass, no errors'); await b.close(); srv.close(); process.exit(errs.length ? 1 : 0);
})();
