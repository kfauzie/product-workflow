// FICTIONAL example (Relaywise). Known answers from the synthetic data (notebooks/make_data.py). Run: node test_mvp.js
const fs = require('fs'), path = require('path');
const html = fs.readFileSync(path.join(__dirname, 'mvp.html'), 'utf8');
const code = html.split('<script id="calc">')[1].split('</script>')[0];
const m = { exports: {} }; new Function('module', code)(m); const C = m.exports;
const I = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/inputs.json')));
const k = I.costs, t = I.thresholds;
let fail = 0;
const near = (name, got, want, tol) => { const ok = Math.abs(got - want) <= tol; if (!ok) fail++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}: ${got.toFixed ? got.toFixed(2) : got} (want ${want})`); };
const is = (name, got, want) => { const ok = got === want; if (!ok) fail++; console.log(`${ok ? 'PASS' : 'FAIL'} ${name}: ${got} (want ${want})`); };
near('Wilson lower bound, 388 of 394', C.wilsonLow(388, 394), 0.9671, 0.0005);
const rec = C.plan(I.categories, 'recommended', k, t), rev = C.plan(I.categories, 'review', k, t), auto = C.plan(I.categories, 'auto', k, t);
near('recommended plan, net a year', rec.annual, 349100, 50);
near('review everything, net a year', rev.annual, 271487, 50);
near('auto everything, net a year', auto.annual, -150807, 50);
near('recommended: agent hours a month', rec.hours, 1313, 1);
near('recommended: wrong answers a month', rec.minor + rec.major, 197, 1);
is('Billing disputes → AI drafts, agent approves', C.recommend(I.categories.find(c => c.name === 'Billing disputes'), t), 'review');
is('Contract and pricing → agents only (small sample)', C.recommend(I.categories.find(c => c.name === 'Contract and pricing'), t), 'human');
is('auto-resolve categories', rec.rows.filter(r => r.mode === 'auto').length, 4);
const sum = rec.rows.reduce((a, r) => a + r.net, 0); near('categories add up to the plan', sum * 12, rec.annual, 0.01);
const L = I.example_labelled_set, withL = C.plan(I.categories.map(c => c.name === L.category ? Object.assign({}, c, L) : c), 'recommended', k, t);
is('labelled set moves Billing disputes to auto-resolve', C.recommend(Object.assign({}, I.categories.find(c => c.name === L.category), L), t), 'auto');
near('plan with the labelled set, net a year', withL.annual, 506769, 50);
console.log(fail ? `${fail} FAILED` : 'All tests pass'); process.exit(fail ? 1 : 0);
